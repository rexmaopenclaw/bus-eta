// Build route-shape-map.js from official hkbus routeFareList data
// Run: node build-route-shape-map.js
// Source: https://data.hkbus.app/routeFareList.min.json
// Output: worker/route-shape-map.js — { `${company}|${route}|${bound}`: `${gtfsId}-${O|I}.json` }
const fs = require('fs');

const data = JSON.parse(fs.readFileSync('routeFareList.min.json', 'utf8'));
const rl = data.routeList;

const map = {};
let skipped = 0;
let used = 0;

for (const key of Object.keys(rl)) {
  const e = rl[key];
  if (!e.gtfsId) { skipped++; continue; }
  const co = Array.isArray(e.co) ? e.co : [];
  if (co.length === 0) { skipped++; continue; }
  const bound = e.bound || {};
  // Suffix follows hkbus-app logic: bound of first company, I else O
  const suffix = bound[co[0]] === 'I' ? 'I' : 'O';
  const file = `${e.gtfsId}-${suffix}.json`;
  const route = String(e.route || '').toUpperCase();
  if (!route) { skipped++; continue; }
  for (const c of co) {
    const b = bound[c];
    if (!b) continue;
    const company = String(c).toUpperCase();
    const bk = `${company}|${route}|${String(b).toUpperCase()}`;
    map[bk] = file;
    used++;
  }
}

const out = '// Auto-generated by build-route-shape-map.js from routeFareList.min.json\n' +
  '// Maps company|route|bound → hkbus route-waypoints file\n' +
  'export const routeShapeMap = ' + JSON.stringify(map) + ';\n';

fs.writeFileSync('worker/route-shape-map.js', out, 'utf8');
console.log(`entries used: ${used}, skipped: ${skipped}, map keys: ${Object.keys(map).length}`);
console.log('sample:', JSON.stringify(Object.entries(map).slice(0, 5)));
